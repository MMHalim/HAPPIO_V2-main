create table if not exists public.sme_list (
  id bigint generated by default as identity primary key,
  name text not null,
  sort_order integer not null default 1,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.sme_list
  add column if not exists name text,
  add column if not exists sort_order integer not null default 1,
  add column if not exists is_active boolean not null default true,
  add column if not exists created_at timestamptz not null default now(),
  add column if not exists updated_at timestamptz not null default now();

do $$
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'sme_list'
      and column_name = 'value'
  ) then
    execute '
      update public.sme_list
      set name = coalesce(nullif(name, ''''), nullif(value, ''''))
    ';
    execute 'drop index if exists sme_list_value_unique_idx';
    execute 'alter table public.sme_list drop column if exists value';
  end if;
end
$$;

create unique index if not exists sme_list_name_unique_idx
  on public.sme_list (name);

create or replace function public.set_sme_list_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_sme_list_updated_at on public.sme_list;
create trigger trg_sme_list_updated_at
before update on public.sme_list
for each row
execute function public.set_sme_list_updated_at();

alter table public.sme_list enable row level security;

do $$
begin
  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public'
      and tablename = 'sme_list'
      and policyname = 'Allow public read access to sme_list'
  ) then
    create policy "Allow public read access to sme_list"
      on public.sme_list
      for select
      to anon, authenticated
      using (true);
  end if;
end
$$;

grant select on public.sme_list to anon, authenticated;
grant all privileges on public.sme_list to service_role;
grant usage, select on sequence public.sme_list_id_seq to service_role;

